export function generateMermaidDiagram(description: string): GeneratedGraphic {
  const mermaidContent = `graph TD
    A[User Request: ${description.slice(0, 30)}] --> B[Question Classification]
    B --> C{Requires Live Data?}
    C -->|Yes: News/Weather/Markets| D[Real-Time Verification Engine]
    C -->|No: Reasoning/Code| E[Claude 3.7 Hybrid Engine]
    D --> F[Multi-Source Cross-Check]
    F --> G[Synthesized Output with Citations]
    E --> G
    G --> H[Interactive Split-Screen Artifacts]`;

  return {
    type: "mermaid",
    content: mermaidContent,
    prompt: description,
    source: "NOVA AI Mermaid Compiler",
  };
}

